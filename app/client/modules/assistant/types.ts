// Shapes of the GM assistant's REST replies (server/lib/assistant, server/modules/95-assistant.js).
// Not part of the game state, so they are not in shared/types.ts.
import type { GameMap } from '../../../shared/types.ts';

/** GET /api/assistant/status (or { error } locally when it failed). */
export interface AssistantStatus {
  enabled?: boolean;
  connected?: boolean;
  busy?: boolean;
  modelLabel?: string;
  budget?: AssistantBudget;
  /** Set by the dock when the status request failed (translated message). */
  error?: string;
}

export interface AssistantBudget {
  spent?: number;
  cap?: number;
  /** spent / cap. */
  ratio?: number;
  allowed?: boolean;
}

/** Entry of GET /api/assistant/conversations. */
export interface ConversationSummary {
  id: string;
  title: string;
  /** Number of proposals waiting for the GM. */
  pending?: number;
}

/** GET /api/assistant/conversations/:id */
export interface Conversation {
  id: string;
  items: ConversationItem[];
  /** Cost of the conversation so far. */
  usd?: number;
}

export type ConversationItem =
  | { type: 'user'; text: string }
  | { type: 'assistant'; text: string }
  | { type: 'tool'; key: string; params?: Record<string, unknown> }
  | { type: 'proposal'; proposal: Proposal }
  | { type: 'notice'; kind?: string; key: string; params?: Record<string, unknown> };

export type ProposalStatus = 'pending' | 'applied' | 'dismissed' | 'failed' | 'partial';

/** NPC template generated by the assistant (preview only: a subset of a bestiary Template). */
export interface ProposalTemplate {
  metatype?: string;
  concept?: string;
  attributes?: Record<string, number | undefined>;
  npc?: { professionalRating?: number | null };
  skills?: Array<{ id?: string; name?: string; rating?: number }>;
  weapons?: Array<{ name?: string; damage?: string; ap?: number | string }>;
}

/** A line of a diff hunk: ' ' kept, '-' removed, '+' added (server/lib/assistant/diff.ts). */
export interface DiffLine {
  op: ' ' | '-' | '+';
  s: string;
}
/** Before/after diff of one field or document. */
export interface FieldDiff {
  field: string;
  hunks: Array<{ skip: number; lines: DiffLine[] }>;
  added: number;
  removed: number;
  /** Lines left out (diff too long). */
  cut?: number;
}

export interface Proposal {
  id: string;
  /** 'map' | 'map_edits' | 'npc' | 'handout' | 'campaign' | 'campaign_edit' | 'doc' (campaign kinds: `sub` says which entry). */
  kind: string;
  sub?: string;
  status: ProposalStatus;
  title: string;
  error?: string;
  result?: { mapId?: string; doc?: string };
  preview?: {
    map?: GameMap;
    template?: ProposalTemplate;
    body?: string;
    text?: string;
    phases?: string[];
    changes?: FieldDiff[];
    /** The change is visible to players (player recap, revealed handout). */
    playersSee?: boolean;
    /** doc: a new document. */
    created?: boolean;
  };
}

/** POST /api/assistant/ask */
export interface AskReply {
  conversationId: string;
}
